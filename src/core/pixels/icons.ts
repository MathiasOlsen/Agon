export const ICON_SIZE = 12;

const ICON_PALETTE: Record<string, ColorKey | null> = {
  ' ': null,
  '.': null,
  '#': 'ink',
  '+': 'accent',
};

export function buildIcon(name: IconName): Grid {
  const rows = GLYPHS[name];
  return gridFromStrings(rows, ICON_PALETTE, ICON_SIZE);
}

export function iconNames(): IconName[] {
  return Object.keys(GLYPHS) as IconName[];
}
